// Writes supabase/seed.sql from lib/catalog.ts and lib/branches.ts.
// Run: npx tsx scripts/generate-seed.ts
import { writeFileSync } from "node:fs";
import { PRICE_LIST_SOURCE, PRICE_SHEETS } from "../lib/catalog";
import { BRANCHES } from "../lib/branches";
import { TIERS } from "../lib/tiers";

const q = (v: unknown) => (v == null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a?: string[]) => (a ? `array[${a.map(q).join(",")}]::text[]` : "null");
const out: string[] = ["-- Generated by scripts/generate-seed.ts. Do not edit by hand.", "begin;"];

for (const b of BRANCHES)
  out.push(`insert into branches (slug,name,city,province,region,address,phones,lat,lng,is_main) values (${[b.slug, b.name, b.city, b.province, b.region, b.address].map(q).join(",")},${arr(b.phones)},${b.lat},${b.lng},${!!b.hq}) on conflict (slug) do nothing;`);

PRICE_SHEETS.forEach((s, i) => {
  out.push(`insert into price_sheets (slug,name,category,handling,unit,columns,terms,sort) values (${[s.slug, s.name, s.category, s.handling, s.unit].map(q).join(",")},${q(JSON.stringify(s.columns))}::jsonb,${arr(s.terms)},${i}) on conflict (slug) do nothing;`);
  s.rows.forEach((r, j) => out.push(`insert into price_sheet_rows values (${q(s.slug)},${q(r.key)},${q(r.label)},${j}) on conflict do nothing;`));
});

// Base list (all branches, all tiers) plus one list per tier with the same temporary prices,
// ready to be edited per tier. Branch-specific lists are added later the same way.
const lists: [string, string | null][] = [["base", null], ...TIERS.map((t) => [t.id, t.id] as [string, string])];
for (const [name, tier] of lists) {
  out.push(`with l as (insert into price_lists (tier,name,effective_from,reason) values (${tier ? `${q(tier)}::price_tier` : "null"},${q(`${PRICE_LIST_SOURCE.title} (${name})`)},${q(PRICE_LIST_SOURCE.effective)},'Temporary list for all tiers from the QC depot price list') returning id)`);
  const vals: string[] = [];
  for (const s of PRICE_SHEETS)
    for (const r of s.rows)
      r.prices.forEach((p, k) => {
        if (p != null) vals.push(`((select id from l),${q(s.slug)},${q(r.key)},${q(s.columns[k].key)},${p})`);
      });
  out.push(`insert into price_list_items values\n  ${vals.join(",\n  ")};`);
}
out.push("commit;");
writeFileSync("supabase/seed.sql", out.join("\n") + "\n");
console.log("wrote supabase/seed.sql");
